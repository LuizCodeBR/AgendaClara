import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';

async function admin(page: Page) {
  const menu = page.getByRole('button', { name: 'Abrir menu', exact: true });
  if (await menu.isVisible()) await menu.click();
  await page.getByRole('button', { name: 'Meu negócio', exact: true }).click();
}
test('responsável cria empresa, configura atendimento, publica, recebe reserva e oculta a página', async ({ page }, testInfo) => {
  test.setTimeout(60000); page.setDefaultTimeout(10000);
  const suffix = testInfo.project.name + '-' + Date.now();
  const business = 'Empresa teste ' + suffix, person = 'Profissional ' + suffix, customer = 'Cliente próprio ' + suffix;
  const email = suffix + '@example.test', password = 'uma frase exclusiva para teste 2030';
  await page.goto('/#/cadastro');
  await page.getByLabel('Nome da empresa', { exact: true }).fill(business);
  await page.getByLabel('Área de atuação', { exact: true }).fill('Consultoria');
  await page.getByLabel('Local de atendimento', { exact: true }).fill('Atendimento online fictício');
  await page.getByLabel('Seu nome', { exact: true }).fill('Ana Teste');
  await page.getByLabel('E-mail de acesso', { exact: true }).fill(email);
  await page.getByLabel('Crie uma senha', { exact: true }).fill(password);
  await page.getByLabel('Confirme a senha', { exact: true }).fill(password);
  const acknowledgement = page.getByRole('checkbox');
  if (await acknowledgement.isVisible()) await acknowledgement.check();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Criar empresa e conta', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sua conta foi criada.', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Abrir confirmação de e-mail', exact: true }).click();
  await expect(page).toHaveURL(/#\/confirmar-email$/);
  await page.getByRole('button', { name: 'Confirmar este e-mail', exact: true }).click();
  await expect(page.getByText(/E-mail confirmado\./)).toBeVisible();
  await page.getByRole('button', { name: 'Voltar ao painel', exact: true }).click();
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar no painel', exact: true }).click();
  await expect(page.getByRole('heading', { name: business, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Nova reserva', exact: true })).toBeDisabled();
  const catalog = await (await page.request.get('/api/admin/catalog')).json();
  expect(catalog.services).toHaveLength(0); expect(catalog.professionals).toHaveLength(0);
  await page.getByRole('button', { name: 'Serviços', exact: true }).click();
  await page.getByLabel('Nome do serviço', { exact: true }).fill('Consulta de teste');
  await page.getByLabel('Descrição', { exact: true }).fill('Serviço fictício próprio');
  await page.getByLabel('Preço (R$)', { exact: true }).fill('50');
  await page.getByRole('button', { name: 'Adicionar ao catálogo', exact: true }).click();
  await expect(page.getByText('Serviço adicionado. Vincule-o aos profissionais em Equipe e horários para liberar reservas.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Equipe e horários', exact: true }).click();
  await page.getByRole('button', { name: 'Cadastrar profissional', exact: true }).click();
  await page.getByLabel('Nome do novo profissional', { exact: true }).fill(person);
  await page.getByLabel('Especialidade do novo profissional', { exact: true }).fill('Consultoria');
  await page.getByRole('button', { name: 'Cadastrar e configurar horários', exact: true }).click();
  await expect(page.getByLabel('Nome do profissional', { exact: true })).toHaveValue(person);
  await page.getByRole('checkbox', { name: 'Atende o serviço Consulta de teste', exact: true }).check();
  const dayIndex = (new Date(catalog.suggestedDate + 'T12:00:00Z').getUTCDay() + 6) % 7;
  const day = ['Segunda-feira', 'Terça-feira', 'Quarta-feira', 'Quinta-feira', 'Sexta-feira', 'Sábado', 'Domingo'][dayIndex];
  await page.getByRole('checkbox', { name: 'Atende ' + day, exact: true }).check();
  await page.getByRole('button', { name: 'Remover intervalo 2 de ' + day, exact: true }).click();
  await page.getByRole('button', { name: 'Salvar cadastro e horários', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Salvar cadastro e horários', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Página de reservas', exact: true }).click();
  await page.getByRole('button', { name: 'Publicar página de reservas', exact: true }).click();
  const link = page.getByLabel('Link para seus clientes', { exact: true });
  await expect(link).toBeVisible();
  const publicUrl = await link.inputValue();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '../.cache/registration-' + testInfo.project.name + '-published.png', fullPage: true });
  await page.getByRole('button', { name: 'Nova reserva', exact: true }).click();
  await expect(page).toHaveURL(publicUrl);
  await page.getByRole('button', { name: '09:00', exact: true }).click();
  await page.getByLabel('Seu nome', { exact: true }).fill(customer);
  await page.getByLabel('Telefone de contato', { exact: true }).fill('11999991234');
  await page.getByRole('button', { name: 'Confirmar agendamento', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Seu horário.*está reservado/ })).toBeVisible();
  await admin(page);
  await page.getByRole('button', { name: 'Minha agenda', exact: true }).click();
  await expect(page.getByRole('heading', { name: customer, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Página de reservas', exact: true }).click();
  await page.getByRole('button', { name: 'Ocultar página de reservas', exact: true }).click();
  await expect(link).toHaveCount(0);
  await page.getByRole('button', { name: 'Minha agenda', exact: true }).click();
  await expect(page.getByRole('heading', { name: customer, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cancelar ' + customer, exact: true }).click();
  await page.getByRole('button', { name: 'Sim, cancelar', exact: true }).click();
  await expect(page.locator('article').filter({ hasText: customer }).getByText('Cancelado', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Sair do painel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Bem-vindo de volta.', exact: true })).toBeVisible();
  await page.goto(publicUrl);
  await expect(page.getByRole('heading', { name: 'Estabelecimento não encontrado', exact: true })).toBeVisible();
});
