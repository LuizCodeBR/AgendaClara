import { test, expect } from '@playwright/test';

test('serviços por profissional filtram a reserva e protegem atendimentos existentes', async ({ page }, testInfo) => {
  const name='Equipe serviços '+testInfo.project.name+' '+Date.now();
  const customer='Cliente serviços '+testInfo.project.name+' '+Date.now();
  await page.goto('/#/painel');
  await page.getByRole('button', { name: 'Barbearia Horizonte Marina · responsável' }).click();
  await page.getByRole('button', { name: 'Entrar no painel', exact: true }).click();
  await page.getByRole('button', { name: 'Equipe e horários', exact: true }).click();
  await page.getByRole('button', { name: 'Cadastrar profissional', exact: true }).click();
  await page.getByLabel('Nome do novo profissional', { exact: true }).fill(name);
  await page.getByLabel('Especialidade do novo profissional', { exact: true }).fill('Serviço específico de teste');
  await page.getByRole('button', { name: 'Cadastrar e configurar horários', exact: true }).click();
  await expect(page.getByLabel('Nome do profissional', { exact: true })).toHaveValue(name);
  await expect(page.getByText('Sem serviços selecionados, este profissional não recebe novas reservas.', { exact: true })).toBeVisible();
  const catalog=await (await page.request.get('/api/admin/catalog')).json();
  const selected=catalog.services[0], other=catalog.services[1];
  await page.getByRole('checkbox', { name: 'Atende o serviço '+selected.name, exact: true }).check();
  const weekday=(new Date(catalog.suggestedDate+'T12:00:00Z').getUTCDay()+6)%7;
  const day=['Segunda-feira','Terça-feira','Quarta-feira','Quinta-feira','Sexta-feira','Sábado','Domingo'][weekday];
  await page.getByRole('checkbox', { name: 'Atende '+day, exact: true }).check();
  await page.getByRole('button', { name: 'Salvar cadastro e horários', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Salvar cadastro e horários', exact: true })).toBeDisabled();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.getByRole('checkbox', { name: 'Atende o serviço '+selected.name, exact: true })).toBeChecked();
  await page.locator('.professional-services').screenshot({path:testInfo.outputPath('services-editor.png')});
  await page.getByRole('button', { name: 'Nova reserva', exact: true }).click();
  await expect(page.getByRole('button', { name:new RegExp(name+'.*Profissional') })).toBeVisible();
  const cards=page.locator('.service-card');
  await cards.filter({has:page.getByText(other.name,{exact:true})}).click();
  await expect(page.getByRole('button', { name:new RegExp(name+'.*Profissional') })).toHaveCount(0);
  await cards.filter({has:page.getByText(selected.name,{exact:true})}).click();
  await page.getByRole('button', { name:new RegExp(name+'.*Profissional') }).click();
  await page.getByRole('button', { name:'09:00',exact:true }).click();
  await page.getByLabel('Seu nome',{exact:true}).fill(customer);
  await page.getByLabel('Telefone de contato',{exact:true}).fill('11999991234');
  await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Seu horário.*está reservado/})).toBeVisible();
  await page.goto('/#/painel');
  await page.getByRole('button',{name:'Equipe e horários',exact:true}).click();
  await page.getByRole('button',{name:new RegExp(name)}).click();
  await expect(page.getByLabel('Nome do profissional',{exact:true})).toHaveValue(name);
  await page.getByRole('checkbox',{name:'Atende o serviço '+selected.name,exact:true}).uncheck();
  await page.getByRole('button',{name:'Salvar cadastro e horários',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('serviço que seria removido');
  await expect(page.getByRole('checkbox',{name:'Atende o serviço '+selected.name,exact:true})).not.toBeChecked();
  await page.getByRole('button',{name:'Descartar alterações',exact:true}).click();
  await expect(page.getByRole('checkbox',{name:'Atende o serviço '+selected.name,exact:true})).toBeChecked();
  await page.getByRole('button',{name:'Minha agenda',exact:true}).click();
  await page.getByRole('button',{name:'Cancelar '+customer,exact:true}).click();
  await page.getByRole('button',{name:'Sim, cancelar',exact:true}).click();
  await expect(page.locator('article').filter({hasText:customer}).getByText('Cancelado',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Equipe e horários',exact:true}).click();
  await page.getByRole('button',{name:new RegExp(name)}).click();
  await expect(page.getByLabel('Nome do profissional',{exact:true})).toHaveValue(name);
  await page.getByRole('checkbox',{name:'Atende o serviço '+selected.name,exact:true}).uncheck();
  await page.getByRole('button',{name:'Salvar cadastro e horários',exact:true}).click();
  await expect(page.getByRole('button',{name:'Salvar cadastro e horários',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Nova reserva',exact:true}).click();
  await expect(page.getByRole('button',{name:new RegExp(name+'.*Profissional')})).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
