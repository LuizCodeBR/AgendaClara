import {test,expect} from '@playwright/test';
test('empresa define prazos, cliente vê as regras e a reserva mantém suas condições',async({page,context},info)=>{
  test.setTimeout(180000);
  const name='Empresa regras '+info.project.name+' '+Date.now(),customer='Cliente regras '+info.project.name+' '+Date.now();
  const email=crypto.randomUUID()+'@example.test',password='frase ficticia exclusiva de teste de regras 2030';
  async function request(path:string,method='GET',body?:unknown,form=false){
    const headers:Record<string,string>={};
    if(method!=='GET'){const csrf=await(await page.request.get('/api/auth/csrf')).json();headers[csrf.headerName]=csrf.token;}
    const r=await page.request.fetch(path,{method,headers,...(body?(form?{form:body as Record<string,string>}:{data:body}):{})});
    expect(r.ok(),method+' '+path).toBe(true);return r.status()===204?null:r.json();
  }
  const registered=await request('/api/auth/register','POST',{requestKey:crypto.randomUUID(),businessName:name,category:'Teste',address:'Online fictício',zoneId:'America/Sao_Paulo',ownerName:'Ana Teste',email,password,demoAcknowledged:true});
  const mail=(await request('/api/auth/demo-mailbox')).find((m:{purpose:string})=>m.purpose==='VERIFY');
  await request('/api/auth/email/confirm','POST',{token:new URLSearchParams(new URL(mail.actionUrl).hash.split('?')[1]).get('token')});
  await request('/api/auth/login','POST',{username:email,password},true);
  const catalog=await request('/api/admin/catalog');
  const service=await request('/api/admin/services','POST',{name:'Consulta de regras',description:'Teste fictício',durationMinutes:30,priceCents:2500});
  const person=await request('/api/admin/professionals','POST',{name:'Pessoa de regras',specialty:'Teste'});
  const weekday=(new Date(catalog.suggestedDate+'T12:00:00Z').getUTCDay()+6)%7+1;
  await request('/api/admin/professionals/'+person.id,'PUT',{...person,serviceIds:[service.id],hours:[{weekday,opensAt:'09:00',closesAt:'18:00'}]});
  const setup=await request('/api/admin/business');
  await request('/api/admin/business/publication','PUT',{published:true,version:setup.version});
  await page.goto('/#/painel');
  await page.getByRole('button',{name:'Regras de agendamento',exact:true}).click();
  await page.getByLabel('Antecedência mínima para reservar',{exact:true}).selectOption('15');
  await page.getByLabel('Antecedência para cancelar pelo cliente',{exact:true}).selectOption('10080');
  await expect(page.getByRole('button',{name:'Minha agenda',exact:true})).toBeDisabled();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Salvar regras de agendamento',exact:true}).click();
  await expect(page.getByText('Regras salvas. Valem para novas reservas; as já confirmadas mantêm suas condições.',{exact:true})).toBeVisible();
  await page.locator('.policy-panel').screenshot({path:info.outputPath('regras-de-agendamento.png')});
  await page.getByRole('button',{name:'Nova reserva',exact:true}).click();
  await expect(page.getByText('168 horas antes',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'09:00',exact:true}).click();
  await page.getByLabel('Seu nome',{exact:true}).fill(customer);
  await page.getByLabel('Telefone de contato',{exact:true}).fill('11999991234');
  await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Seu horário.*está reservado/})).toBeVisible();
  const link=await page.getByLabel('Link privado da reserva').inputValue();
  const portal=await context.newPage();await portal.goto(link);
  await expect(portal.getByText(customer,{exact:true})).toBeVisible();
  await expect(portal.getByRole('button',{name:'Cancelar minha reserva',exact:true})).toHaveCount(0);
  await expect(portal.getByRole('button',{name:'Remarcar minha reserva',exact:true})).toBeVisible();
  await expect(portal.getByText('168 horas antes',{exact:true})).toBeVisible();
  await page.goto('/#/painel');
  await page.getByRole('button',{name:'Regras de agendamento',exact:true}).click();
  await page.getByLabel('Antecedência mínima para reservar',{exact:true}).selectOption('10080');
  await page.getByLabel('Antecedência para cancelar pelo cliente',{exact:true}).selectOption('0');
  await page.getByRole('button',{name:'Salvar regras de agendamento',exact:true}).click();
  await expect(page.getByText('Regras salvas. Valem para novas reservas; as já confirmadas mantêm suas condições.',{exact:true})).toBeVisible();
  await portal.reload();await expect(portal.getByText('168 horas antes',{exact:true})).toBeVisible();
  await expect(portal.getByRole('button',{name:'Cancelar minha reserva',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Minha agenda',exact:true}).click();
  await page.getByRole('button',{name:'Remarcar '+customer,exact:true}).click();
  await page.getByRole('button',{name:'10:00',exact:true}).click();
  await page.getByRole('button',{name:'Confirmar remarcação',exact:true}).click();
  await expect(page.getByText('Agendamento remarcado.',{exact:true})).toBeVisible();
  await expect(page.locator('article').filter({hasText:customer}).getByText('10:00',{exact:true})).toBeVisible();
  await portal.reload();await expect(portal.getByText('168 horas antes',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancelar '+customer,exact:true}).click();
  await page.getByRole('button',{name:'Sim, cancelar',exact:true}).click();
  await expect(page.locator('article').filter({hasText:customer}).getByText('Cancelado',{exact:true})).toBeVisible();
  await portal.reload();await expect(portal.getByText('Cancelada',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Página de reservas',exact:true}).click();
  await page.getByRole('button',{name:'Ocultar página de reservas',exact:true}).click();
  await expect(page.getByLabel('Link para seus clientes',{exact:true})).toHaveCount(0);
  await portal.close();
  expect((await request('/api/admin/business/booking-policy')).version).toBe(2);
  expect(registered.businessId).toBeTruthy();
});
