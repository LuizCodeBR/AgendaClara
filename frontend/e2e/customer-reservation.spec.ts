import {test,expect} from '@playwright/test';

test('cliente gerencia a própria reserva e usa duas reservas em abas independentes',async({page,context},info)=>{
  const name='Cliente privado '+info.project.name+' '+Date.now();
  await page.goto('/#/agendar/barbearia-horizonte');
  await page.getByRole('button',{name:/^\d{2}:\d{2}$/}).first().click();
  await page.getByLabel('Seu nome',{exact:true}).fill(name);
  await page.getByLabel('Telefone de contato',{exact:true}).fill('11999991234');
  await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Seu horário.*está reservado/})).toBeVisible();
  const link=await page.getByLabel('Link privado da reserva').inputValue();
  const token=new URLSearchParams(new URL(link).hash.split('?')[1]).get('token')!;
  const urls:string[]=[];page.on('request',request=>urls.push(request.url()));
  await page.getByRole('link',{name:'Gerenciar minha reserva',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Minha reserva',exact:true})).toBeVisible();
  await expect(page.getByText(name,{exact:true})).toBeVisible();
  await expect(page).toHaveURL(/#\/minha-reserva\?reserva=[a-f0-9-]{36}$/);
  expect(page.url()).not.toContain(token);
  expect(urls.some(url=>url.includes(token))).toBe(false);
  expect(await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}))).not.toContain(token);
  expect(await page.evaluate(()=>document.cookie)).not.toContain('AGENDA_CUSTOMER_ACCESS');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.customer-details').screenshot({path:info.outputPath('minha-reserva.png')});
  const price=await page.locator('dd').nth(5).innerText();
  await page.getByRole('button',{name:'Remarcar minha reserva',exact:true}).click();
  await page.getByRole('button',{name:/^\d{2}:\d{2}$/}).last().click();
  await page.getByRole('button',{name:'Confirmar novo horário',exact:true}).click();
  await expect(page.getByText('Reserva remarcada. Confira o novo horário abaixo.',{exact:true})).toBeVisible();
  expect(await page.locator('dd').nth(5).innerText()).toBe(price);
  await page.reload();await expect(page.getByText(name,{exact:true})).toBeVisible();
  // Another booking in the same browser must not change the first tab's target.
  const other=await context.newPage();const name2=name+' segunda';
  await other.goto('/#/agendar/barbearia-horizonte');
  await other.getByRole('button',{name:/^\d{2}:\d{2}$/}).first().click();
  await other.getByLabel('Seu nome',{exact:true}).fill(name2);
  await other.getByLabel('Telefone de contato',{exact:true}).fill('11999991234');
  await other.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  await expect(other.getByLabel('Link privado da reserva')).toBeVisible();
  await other.getByRole('link',{name:'Gerenciar minha reserva',exact:true}).click();
  await expect(other.getByText(name2,{exact:true})).toBeVisible();
  await page.reload();await expect(page.getByText(name,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancelar minha reserva',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Cancelar sua reserva?',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Sim, cancelar minha reserva',exact:true}).click();
  await expect(page.getByText('Reserva cancelada. O horário foi liberado.',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Remarcar minha reserva',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Encerrar acesso neste navegador',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Abra seu link privado',exact:true})).toBeVisible();
  await other.reload();await expect(other.getByText(name2,{exact:true})).toBeVisible();
  await other.getByRole('button',{name:'Cancelar minha reserva',exact:true}).click();
  await other.getByRole('button',{name:'Sim, cancelar minha reserva',exact:true}).click();
  await expect(other.getByText('Reserva cancelada. O horário foi liberado.',{exact:true})).toBeVisible();
  await other.close();
});

test('código público não abre reserva e responsável pode revogar link privado',async({page,context},info)=>{
  await page.goto('/#/minha-reserva');
  await page.getByLabel('Link ou código privado').fill('PUBLICO123');
  await page.getByRole('button',{name:'Acessar minha reserva',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('código público');
  const name='Revogação privada '+info.project.name+' '+Date.now();
  await page.goto('/#/agendar/barbearia-horizonte');
  await page.getByRole('button',{name:/^\d{2}:\d{2}$/}).first().click();
  await page.getByLabel('Seu nome',{exact:true}).fill(name);
  await page.getByLabel('Telefone de contato',{exact:true}).fill('11999991234');
  await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click();
  const link=await page.getByLabel('Link privado da reserva').inputValue();
  const customer=await context.newPage();await customer.goto(link);
  await expect(customer.getByText(name,{exact:true})).toBeVisible();
  await page.goto('/#/painel');
  await page.getByRole('button',{name:'Barbearia Horizonte Marina · responsável',exact:true}).click();
  await page.getByRole('button',{name:'Entrar no painel',exact:true}).click();
  await page.getByRole('button',{name:'Acesso do cliente '+name,exact:true}).click();
  await expect(page.getByRole('heading',{name:'Acesso privado do cliente',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Gerar novo link privado',exact:true}).click();
  const fresh=await page.getByLabel('Link privado da reserva').inputValue();expect(fresh).not.toBe(link);
  await customer.reload();await expect(customer.getByRole('alert')).toContainText('inválido ou expirou');
  await customer.goto(fresh);await expect(customer.getByText(name,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Revogar acesso do cliente',exact:true}).click();
  await customer.reload();await expect(customer.getByRole('alert')).toContainText('inválido ou expirou');
  await page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true}).last().click();
  await page.getByRole('button',{name:'Cancelar '+name,exact:true}).click();
  await page.getByRole('button',{name:'Sim, cancelar',exact:true}).click();
  await expect(page.locator('article').filter({hasText:name}).getByText('Cancelado',{exact:true})).toBeVisible();
  await customer.close();
});
