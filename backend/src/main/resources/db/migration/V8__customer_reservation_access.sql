ALTER TABLE appointment ADD COLUMN version INTEGER NOT NULL DEFAULT 0;
ALTER TABLE appointment ADD CONSTRAINT uq_appointment_business UNIQUE (id,business_id);
CREATE TABLE appointment_access (
  appointment_id UUID NOT NULL,
  business_id UUID NOT NULL,
  generation INTEGER NOT NULL CHECK (generation > 0),
  token_digest CHAR(64) UNIQUE,
  issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked_at TIMESTAMP WITH TIME ZONE,
  issue_request_key UUID,
  PRIMARY KEY (appointment_id,business_id),
  FOREIGN KEY (appointment_id,business_id) REFERENCES appointment(id,business_id) ON DELETE CASCADE
);
CREATE TABLE appointment_customer_session (
  id UUID PRIMARY KEY,
  session_seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  appointment_id UUID NOT NULL,
  business_id UUID NOT NULL,
  access_generation INTEGER NOT NULL CHECK (access_generation > 0),
  secret_digest CHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  FOREIGN KEY (appointment_id,business_id) REFERENCES appointment_access(appointment_id,business_id) ON DELETE CASCADE
);
CREATE INDEX idx_customer_session_expiry ON appointment_customer_session(appointment_id,expires_at);
